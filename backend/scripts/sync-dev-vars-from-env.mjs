#!/usr/bin/env node
/**
 * Write backend/.dev.vars from repo root .env (PANDA_TALK_SUPABASE_*).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const envPath = path.join(root, '.env')
const outPath = path.join(root, 'backend', '.dev.vars')

function parseEnv(text) {
  const map = {}
  for (const line of text.split('\n')) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    const i = t.indexOf('=')
    if (i === -1) continue
    map[t.slice(0, i).trim()] = t.slice(i + 1).trim()
  }
  return map
}

if (!fs.existsSync(envPath)) {
  console.error('Missing root .env — copy from .env.example')
  process.exit(1)
}

const env = parseEnv(fs.readFileSync(envPath, 'utf8'))
const url = env.PANDA_TALK_SUPABASE_URL
const anon = env.PANDA_TALK_SUPABASE_ANON_KEY
const serviceRole = env.PANDA_TALK_SUPABASE_SERVICE_ROLE_KEY
if (!url || !anon) {
  console.error('.env needs PANDA_TALK_SUPABASE_URL and PANDA_TALK_SUPABASE_ANON_KEY')
  process.exit(1)
}

const body = `# Generated by sync-dev-vars-from-env.mjs — do not commit
SUPABASE_URL=${url}
SUPABASE_ANON_KEY=${anon}
${serviceRole ? `SUPABASE_SERVICE_ROLE_KEY=${serviceRole}\n` : ''}
`
fs.writeFileSync(outPath, body)
console.log(`Wrote ${outPath}`)
